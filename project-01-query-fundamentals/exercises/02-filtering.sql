2. 使用比較運算子：
   =
   <>
   >
   <
   >=
   <=

3. 使用邏輯運算子：
   AND
   OR
   NOT

4. 使用：
   IN
   BETWEEN
   LIKE

5. 理解 AND / OR 混合時為什麼應該使用括號。

使用資料表：

    track
    customer
    invoice

目前仍然不使用：

    JOIN
    GROUP BY
    HAVING
    Subquery
    CTE

===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track;

-------------------------------------------------------
-- 加入 WHERE

SELECT
    track_id,
    name,
    unit_price
FROM track
WHERE unit_price = 0.99;

/*
===============================================================================
01. 等於 =
===============================================================================

找出單價等於 0.99 的歌曲。

WHERE 後面的：

    unit_price = 0.99

是一個 Boolean Condition。

對每一列資料來說，
這個條件可能得到：

    TRUE
    FALSE

目前先不處理 NULL 所產生的 UNKNOWN。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
WHERE unit_price = 0.99;

SELECT
    track_id,
    name
FROM track
WHERE name = 'For Those About To Rock (We Salute You)';

/*
===============================================================================
02. 不等於 <>
===============================================================================

找出價格不是 0.99 的歌曲。

<> 是 SQL Standard 常見的不等於寫法。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
WHERE unit_price <> 0.99;

/*
===============================================================================
03. 大於 >
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds > 300000;

/*
===============================================================================
04. 小於 <
===============================================================================

找出長度少於 2 分鐘的歌曲。

2 分鐘：

    2 * 60 * 1000
    = 120000 milliseconds
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds < 120000;

/*
===============================================================================
05. 大於等於 >=
===============================================================================

包含邊界值本身。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds >= 300000;

/*
===============================================================================
04. 小於 <
===============================================================================

找出長度少於 2 分鐘的歌曲。

2 分鐘：

    2 * 60 * 1000
    = 120000 milliseconds
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds < 120000;

/*
===============================================================================
05. 大於等於 >=
===============================================================================

包含邊界值本身。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds >= 300000;

/*
===============================================================================
06. 小於等於 <=
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds <= 120000;

/*
===============================================================================
07. AND
===============================================================================

兩個 Condition 都必須是 TRUE。

條件 1：

    unit_price = 0.99

條件 2：

    milliseconds > 300000

只有兩個條件都成立的 Row 才會留下。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds,
    unit_price
FROM track
WHERE
    unit_price = 0.99
    AND milliseconds > 300000;

/*
===============================================================================
08. 多個 AND
===============================================================================

找：

1. 價格 = 0.99
2. 播放時間 >= 180000
3. 播放時間 <= 300000
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds,
    unit_price
FROM track
WHERE
    unit_price = 0.99
    AND milliseconds >= 180000
    AND milliseconds <= 300000;

/*
===============================================================================
09. OR
===============================================================================

找出價格為：

    0.99

或：

    1.99

的歌曲。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
WHERE
    unit_price = 0.99
    OR unit_price = 1.99;

/*
===============================================================================
10. AND + OR + Parentheses
===============================================================================

AND 和 OR 同時出現時，主動使用括號。

需求：

價格是：

    0.99
    或
    1.99

而且：

播放時間超過 5 分鐘。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price,
    milliseconds
FROM track
WHERE
    (
        unit_price = 0.99
        OR unit_price = 1.99
    )
    AND milliseconds > 300000;

/*
===============================================================================
11. NOT
===============================================================================

找出 unit_price 不是 0.99 的歌曲。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
WHERE NOT unit_price = 0.99;

/*
===============================================================================
12. IN
===============================================================================

IN 適合判斷：

某個值是否存在於一組候選值之中。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
WHERE unit_price IN (
    0.99,
    1.99
);

/*
===============================================================================
13. NOT IN
===============================================================================

找出不是指定價格的歌曲。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
WHERE unit_price NOT IN (
    0.99,
    1.99
);

/*
===============================================================================
14. BETWEEN
===============================================================================

BETWEEN 包含上下界。

下面：

    BETWEEN 180000 AND 300000

等同：

    >= 180000
    AND
    <= 300000
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds BETWEEN 180000 AND 300000;

/*
===============================================================================
15. NOT BETWEEN
===============================================================================

找出播放時間不在 3～5 分鐘範圍內的歌曲。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
WHERE milliseconds NOT BETWEEN 180000 AND 300000;

/*
===============================================================================
16. LIKE - Prefix
===============================================================================

'A%'

代表：

    第一個字元必須是 A

後面：

    可以有任意數量的字元。
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
WHERE name LIKE 'A%';

/*
===============================================================================
17. LIKE - Suffix
===============================================================================

'%Love'

代表：

前面可以有任意字元，
但最後必須是 Love。
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
WHERE name LIKE '%Love';

/*
===============================================================================
18. LIKE - Contains
===============================================================================

'%Love%'

代表：

Love 前後都可以有任意字元。

也就是：

字串只要「包含 Love」即可。
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
WHERE name LIKE '%Love%';

/*
===============================================================================
19. LIKE + _
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
WHERE name LIKE 'A_';

/*
===============================================================================
20. Customer + WHERE
===============================================================================
*/

SELECT
    customer_id,
    first_name,
    last_name,
    country
FROM customer
WHERE country = 'Brazil';

/*
===============================================================================
21. Invoice Total
===============================================================================

找出 Total 超過 10 的 Invoice。
===============================================================================
*/

SELECT
    invoice_id,
    customer_id,
    total
FROM invoice
WHERE total > 10;

