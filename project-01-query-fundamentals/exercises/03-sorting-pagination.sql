/*
===============================================================================
01. 沒有 ORDER BY 時，不保證查詢結果順序
===============================================================================

下面的查詢可能看起來剛好按照：

    track_id

由小到大排列。

但是 SQL 並沒有保證沒有 ORDER BY 時的資料順序。

資料庫可能因為：

    Index
    Query Planner
    資料異動
    VACUUM
    執行計畫

而使用不同方式取得資料。

因此：

如果需求有明確的排序規則，
就必須使用 ORDER BY。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track;


/*
===============================================================================
02. ORDER BY ASC
===============================================================================

ASC：

    Ascending

表示升冪排序。

數字：

    小 → 大

文字：

    依照資料庫的排序規則由前往後排列。

ASC 其實是 ORDER BY 的預設排序方向。

所以：

    ORDER BY track_id;

與：

    ORDER BY track_id ASC;

效果相同。

學習階段先明確寫出 ASC。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
ORDER BY track_id ASC;


/*
===============================================================================
03. ORDER BY DESC
===============================================================================

DESC：

    Descending

表示降冪排序。

數字：

    大 → 小

下面會讓最大的 track_id 排在前面。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
ORDER BY track_id DESC;


/*
===============================================================================
04. 對數值欄位排序
===============================================================================

milliseconds：

    歌曲播放時間
    單位為毫秒。

下面按照播放時間：

    短 → 長
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
ORDER BY milliseconds ASC;


/*
下面則按照播放時間：

    長 → 短
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
ORDER BY milliseconds DESC;


/*
===============================================================================
05. 對文字欄位排序
===============================================================================

ORDER BY 不只能處理數字。

文字：

    varchar
    text

也可以排序。

實際字串排列方式會受到：

    Collation
    Locale
    大小寫規則

等因素影響。

Project 1 目前只需要理解：
文字欄位本身也能 ORDER BY。
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
ORDER BY name ASC;


/*
反向排序。
*/

SELECT
    track_id,
    name
FROM track
ORDER BY name DESC;


/*
===============================================================================
06. 多欄位排序
===============================================================================

ORDER BY 可以同時指定多個排序欄位。

下面的規則：

第一優先：

    unit_price ASC

第二優先：

    name ASC

也就是：

先按照價格排序。

如果兩筆資料價格相同，
才使用 name 決定彼此順序。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
ORDER BY
    unit_price ASC,
    name ASC;


/*
===============================================================================
07. 不同欄位可以使用不同排序方向
===============================================================================

下面的規則：

第一優先：

    unit_price DESC

    價格高的排前面。

第二優先：

    name ASC

    價格相同時，
    名稱由前往後排列。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
ORDER BY
    unit_price DESC,
    name ASC;


/*
===============================================================================
08. 使用唯一欄位作為 Tie-breaker
===============================================================================

如果只寫：

    ORDER BY unit_price DESC

很多歌曲的價格可能完全相同。

例如：

    0.99
    0.99
    0.99
    0.99

這些資料彼此之間沒有進一步指定順序。

如果需要較穩定、明確的查詢結果，
可以再加入唯一欄位：

    track_id

作為第二排序條件。

這種第二條排序規則通常可以稱為：

    tie-breaker
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
ORDER BY
    unit_price DESC,
    track_id ASC;


/*
===============================================================================
09. WHERE + ORDER BY
===============================================================================

前一個 Step 已經學過 WHERE。

WHERE：

    決定哪些 Rows 留下。

ORDER BY：

    決定留下來的 Rows 如何排列。

需求：

    只找價格為 0.99 的歌曲。

然後：

    播放時間由長到短。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds,
    unit_price
FROM track
WHERE unit_price = 0.99
ORDER BY milliseconds DESC;


/*
===============================================================================
10. WHERE + 多欄位 ORDER BY
===============================================================================

需求：

價格：

    0.99
    或
    1.99

排序：

1. milliseconds DESC
2. track_id ASC

其中 track_id 用來讓相同播放時間的資料具有明確順序。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds,
    unit_price
FROM track
WHERE unit_price IN (
    0.99,
    1.99
)
ORDER BY
    milliseconds DESC,
    track_id ASC;


/*
===============================================================================
11. LIMIT
===============================================================================

LIMIT 用來限制：

    最多回傳多少筆資料。

下面：

    LIMIT 10

代表：

    最多回傳 10 Rows。

注意：

單純 LIMIT 10 並不代表：

    Top 10

因為如果沒有 ORDER BY，
SQL 並沒有定義：

    哪十筆算是「前十筆」。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
LIMIT 10;


/*
===============================================================================
12. ORDER BY + LIMIT
===============================================================================

需求：

找出播放時間最長的 10 首歌曲。

必須先：

    ORDER BY milliseconds DESC

把最長的排在前面。

再：

    LIMIT 10

取得前 10 筆。

這時候才具有真正的：

    Top 10

意義。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
ORDER BY
    milliseconds DESC,
    track_id ASC
LIMIT 10;


/*
===============================================================================
13. 價格最高的 10 首歌曲
===============================================================================

排序：

1. unit_price DESC
2. track_id ASC

最後：

    LIMIT 10

取得結果中的前十筆。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
ORDER BY
    unit_price DESC,
    track_id ASC
LIMIT 10;


/*
===============================================================================
14. OFFSET
===============================================================================

OFFSET：

    跳過指定數量的 Rows。

下面：

    LIMIT 10
    OFFSET 10

意思是：

先跳過：

    10 筆

再取得：

    10 筆。

如果每頁 10 筆：

    OFFSET 0
        → 第 1 頁

    OFFSET 10
        → 第 2 頁

    OFFSET 20
        → 第 3 頁
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
ORDER BY track_id ASC
LIMIT 10
OFFSET 10;


/*
===============================================================================
15. 第一頁
===============================================================================

假設：

    page_size = 10

第 1 頁：

    OFFSET 0
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
ORDER BY track_id ASC
LIMIT 10
OFFSET 0;


/*
===============================================================================
16. 第二頁
===============================================================================

每頁：

    10 筆

第 2 頁：

    OFFSET 10
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
ORDER BY track_id ASC
LIMIT 10
OFFSET 10;


/*
===============================================================================
17. 第三頁
===============================================================================

每頁：

    10 筆

第 3 頁：

    OFFSET 20
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
ORDER BY track_id ASC
LIMIT 10
OFFSET 20;


/*
===============================================================================
18. 分頁 OFFSET 計算公式
===============================================================================

公式：

    OFFSET = (page - 1) * page_size

例如：

    page = 5
    page_size = 20

計算：

    OFFSET
    = (5 - 1) * 20
    = 80

因此第 5 頁：

    LIMIT 20
    OFFSET 80
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
ORDER BY track_id ASC
LIMIT 20
OFFSET 80;


/*
===============================================================================
19. 分頁必須搭配 ORDER BY
===============================================================================

下面雖然可以執行：

    LIMIT 10
    OFFSET 10

但是沒有 ORDER BY。

因此：

    第一頁
    第二頁
    第三頁

並沒有保證使用固定順序。

分頁查詢應該明確指定 ORDER BY。

尤其是 API 分頁時更重要。
===============================================================================
*/

SELECT
    track_id,
    name
FROM track
ORDER BY track_id ASC
LIMIT 10
OFFSET 10;


/*
===============================================================================
20. 分頁最好使用穩定排序
===============================================================================

下面只有：

    ORDER BY unit_price DESC

可能不夠穩定。

因為很多歌曲有相同價格。

因此加入：

    track_id ASC

作為 Tie-breaker。

這樣每一筆 Row 在排序中都有明確位置。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track
ORDER BY
    unit_price DESC,
    track_id ASC
LIMIT 10
OFFSET 10;


/*
===============================================================================
21. Invoice 日期排序
===============================================================================

日期 / 時間欄位也可以 ORDER BY。

DESC：

    最新的時間排前面。

ASC：

    最舊的時間排前面。
===============================================================================
*/

SELECT
    invoice_id,
    customer_id,
    invoice_date,
    total
FROM invoice
ORDER BY invoice_date DESC;


/*
===============================================================================
22. 最新的 10 張 Invoice
===============================================================================

第一排序：

    invoice_date DESC

第二排序：

    invoice_id DESC

如果兩筆 Invoice 剛好時間完全相同，
再由 invoice_id 決定順序。
===============================================================================
*/

SELECT
    invoice_id,
    customer_id,
    invoice_date,
    total
FROM invoice
ORDER BY
    invoice_date DESC,
    invoice_id DESC
LIMIT 10;


/*
===============================================================================
23. Customer 多欄位排序
===============================================================================

排序規則：

第一：

    country

如果 country 相同：

第二：

    last_name

如果 last_name 也相同：

第三：

    first_name
===============================================================================
*/

SELECT
    customer_id,
    first_name,
    last_name,
    country
FROM customer
ORDER BY
    country ASC,
    last_name ASC,
    first_name ASC;


/*
===============================================================================
24. ORDER BY 可以使用 SELECT Alias
===============================================================================

Step 02 學過計算欄位。

下面：

    milliseconds / 60000.0

計算歌曲分鐘數。

並取 Alias：

    duration_minutes

ORDER BY 可以使用這個 Alias。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds / 60000.0 AS duration_minutes
FROM track
ORDER BY duration_minutes DESC;


/*
===============================================================================
25. 不建議使用欄位位置排序
===============================================================================

PostgreSQL 支援：

    ORDER BY 3

其中：

    3

代表 SELECT Result 的第三個欄位。

下面：

    1 = track_id
    2 = name
    3 = milliseconds

所以：

    ORDER BY 3 DESC

等同：

    ORDER BY milliseconds DESC

但是這種寫法可讀性較差。

而且只要 SELECT 欄位位置改變，
ORDER BY 的意義也可能跟著改變。

因此學習與一般程式碼中，
優先直接寫欄位名稱。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
ORDER BY 3 DESC;


/*
推薦：
*/

SELECT
    track_id,
    name,
    milliseconds
FROM track
ORDER BY milliseconds DESC;


/*
===============================================================================
26. PostgreSQL 補充：NULLS FIRST / NULLS LAST
===============================================================================

這是 PostgreSQL 可以明確控制 NULL 排序位置的方式。

例如 composer 可能是 NULL。

NULLS LAST：

    NULL 放最後。

NULLS FIRST：

    NULL 放最前面。

NULL 的完整概念會在後續 Step 專門學習。

目前只需要知道 PostgreSQL 有這個功能。
===============================================================================
*/

SELECT
    track_id,
    name,
    composer
FROM track
ORDER BY
    composer ASC NULLS LAST;


/*
===============================================================================
27. OFFSET Pagination 的效能提醒
===============================================================================

目前 Project 1 使用：

    LIMIT
    OFFSET

是為了學習基本 Pagination。

例如：

    LIMIT 20
    OFFSET 100000

在大型資料庫可能有效能問題。

後面的 SQL 效能專案會再學：

    Offset Pagination

與：

    Keyset Pagination

目前不用處理最佳化問題。

先把：

    ORDER BY
    LIMIT
    OFFSET

的基本語意理解清楚即可。
===============================================================================
*/


