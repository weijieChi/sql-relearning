       AND
       OR
       NOT

   時可能產生 UNKNOWN。

主要使用資料表：

    track
    customer

===============================================================================
*/


/*
===============================================================================
01. NULL 是什麼？
===============================================================================

NULL 可以表示：

    不知道
    尚未提供
    不適用
    缺少資料

實際意義仍然取決於：

    Database Schema
    Business Rule

重要：

NULL 不等於：

    0

NULL 不等於：

    ''

NULL 不等於：

    false

NULL 也不是字串：

    'NULL'

它是一種特殊的 SQL 狀態。
===============================================================================
*/


/*
===============================================================================
02. 先找出可能含 NULL 的欄位
===============================================================================

Chinook 的 track.composer：

有些歌曲有 Composer，
有些歌曲沒有 Composer 資料。

先直接觀察：
===============================================================================
*/

SELECT
    track_id,
    name,
    composer
FROM track
ORDER BY track_id ASC;


/*
===============================================================================
03. 錯誤觀念：column = NULL
===============================================================================

很多程式語言會寫：

    value == null

所以剛開始學 SQL 很容易寫成：

    composer = NULL

但是 SQL 的 NULL 不是一般值。

因此下面這個條件：

    composer = NULL

不會得到我們直覺想像的結果。
===============================================================================
*/

SELECT
    track_id,
    name,
    composer
FROM track
WHERE composer = NULL;


/*
通常結果會是：

    0 rows

原因不是：

    track 裡沒有 NULL。

而是：

    composer = NULL

這個比較結果不是 TRUE，
而是：

    UNKNOWN。
*/


/*
===============================================================================
04. 正確方式：IS NULL
===============================================================================

要判斷某個欄位是不是 NULL，
必須使用：

    IS NULL
===============================================================================
*/

SELECT
    track_id,
    name,
    composer
FROM track
WHERE composer IS NULL;


/*
這才表示：

    找出 composer 沒有資料的歌曲。
*/


/*
===============================================================================
05. IS NOT NULL
===============================================================================

反過來：

    找出 composer 有資料的歌曲。
===============================================================================
*/

SELECT
    track_id,
    name,
    composer
FROM track
WHERE composer IS NOT NULL;


/*
===============================================================================
06. NULL 不等於空字串
===============================================================================

空字串：

    ''

代表：

    有一個字串，
    只是長度為 0。

NULL：

    沒有值 / 未知值。

所以：

    ''

和：

    NULL

是不同的東西。

PostgreSQL 會明確區分這兩者。
===============================================================================
*/


/*
找真正的空字串。
*/

SELECT
    track_id,
    name,
    composer
FROM track
WHERE composer = '';


/*
找 NULL。
*/

SELECT
    track_id,
    name,
    composer
FROM track
WHERE composer IS NULL;


/*
這兩個 Query 的語意完全不同。
*/


/*
===============================================================================
07. NULL 也不等於 0
===============================================================================

例如：

    0

是一個真正存在的 Numeric Value。

而：

    NULL

表示沒有已知數值。

因此：

    price = 0

和：

    price IS NULL

是兩件完全不同的事情。
===============================================================================
*/


/*
===============================================================================
08. SQL 的三值邏輯
===============================================================================

大多數程式語言常讓我們習慣：

    TRUE
    FALSE

但 SQL 還多一個：

    UNKNOWN

所以 SQL Condition 可能有三種結果：

    TRUE
    FALSE
    UNKNOWN
===============================================================================
*/


/*
例如：

    unit_price = 0.99

如果 unit_price = 0.99：

    TRUE

如果 unit_price = 1.99：

    FALSE

如果 unit_price = NULL：

    UNKNOWN
*/


/*
===============================================================================
09. 為什麼 NULL = NULL 不是 TRUE？
===============================================================================

直覺可能會認為：

    NULL = NULL

應該是 TRUE。

但是 NULL 的意思比較接近：

    unknown value

假設：

    A = unknown
    B = unknown

你不能因為兩邊都不知道，
就證明：

    A = B

所以：

    NULL = NULL

結果仍然是：

    UNKNOWN
===============================================================================
*/


/*
可以直接測試：
*/

SELECT
    NULL = NULL AS result;


/*
也可以測試：
*/

SELECT
    NULL <> NULL AS result;


/*
兩個結果都不會是 TRUE。
*/


/*
===============================================================================
10. WHERE 只留下 TRUE
===============================================================================

這是理解 NULL 非常重要的一點。

WHERE 會保留：

    TRUE

但不保留：

    FALSE
    UNKNOWN

所以：

    WHERE composer = NULL

每一列的結果都是：

    UNKNOWN

因此全部被 WHERE 排除。
===============================================================================
*/


/*
可以把它想成：

Row 1:
composer = 'AC/DC'

'AC/DC' = NULL
    ↓
UNKNOWN
    ↓
不留下


Row 2:
composer = NULL

NULL = NULL
    ↓
UNKNOWN
    ↓
也不留下
*/


/*
所以：

    = NULL

無法用來找 NULL。
*/


/*
===============================================================================
11. customer.company
===============================================================================

Customer 也有很適合練 NULL 的欄位：

    company

有些 Customer 是公司客戶，
有些沒有填 Company。
===============================================================================
*/

SELECT
    customer_id,
    first_name,
    last_name,
    company
FROM customer
ORDER BY customer_id ASC;


/*
找沒有 company 的 Customer：
*/

SELECT
    customer_id,
    first_name,
    last_name,
    company
FROM customer
WHERE company IS NULL;


/*
找有 company 的 Customer：
*/

SELECT
    customer_id,
    first_name,
    last_name,
    company
FROM customer
WHERE company IS NOT NULL;


/*
===============================================================================
12. customer.fax
===============================================================================

fax 也是非常適合觀察 NULL 的欄位。
===============================================================================
*/

SELECT
    customer_id,
    first_name,
    last_name,
    fax
FROM customer;


/*
沒有 Fax：
*/

SELECT
    customer_id,
    first_name,
    last_name,
    fax
FROM customer
WHERE fax IS NULL;


/*
有 Fax：
*/

SELECT
    customer_id,
    first_name,
    last_name,
    fax
FROM customer
WHERE fax IS NOT NULL;


/*
===============================================================================
13. NULL + AND
===============================================================================

現在開始碰 SQL 三值邏輯。

AND 的一般概念：

    TRUE AND TRUE
        → TRUE

    TRUE AND FALSE
        → FALSE

但是如果有 UNKNOWN：

    TRUE AND UNKNOWN
        → UNKNOWN

    FALSE AND UNKNOWN
        → FALSE
===============================================================================
*/


/*
例如：

如果 composer 是 NULL：

    composer = 'AC/DC'

结果不是 FALSE，
而是 UNKNOWN。

所以：

    unit_price = 0.99
    AND composer = 'AC/DC'

如果：

    unit_price = 0.99
        → TRUE

    composer = NULL
        → UNKNOWN

最後：

    TRUE AND UNKNOWN
        → UNKNOWN

WHERE 不會留下這一列。
*/


SELECT
    track_id,
    name,
    composer,
    unit_price
FROM track
WHERE
    unit_price = 0.99
    AND composer = 'AC/DC';


/*
===============================================================================
14. NULL + OR
===============================================================================

OR 的部分規則：

    TRUE OR UNKNOWN
        → TRUE

    FALSE OR UNKNOWN
        → UNKNOWN
===============================================================================
*/


/*
假設：

    unit_price = 0.99
        → TRUE

    composer = NULL
        → UNKNOWN

那：

    TRUE OR UNKNOWN
        → TRUE

所以這筆資料仍然會留下。
*/


SELECT
    track_id,
    name,
    composer,
    unit_price
FROM track
WHERE
    unit_price = 0.99
    OR composer = 'AC/DC';


/*
===============================================================================
15. NOT + UNKNOWN
===============================================================================

NOT TRUE
    → FALSE

NOT FALSE
    → TRUE

NOT UNKNOWN
    → UNKNOWN

所以：

    NOT (composer = 'AC/DC')

並不表示：

    所有不是 AC/DC 的資料，包括 NULL。

如果 composer 是 NULL：

    composer = 'AC/DC'
        → UNKNOWN

    NOT UNKNOWN
        → UNKNOWN

WHERE 仍然不會保留。
===============================================================================
*/


SELECT
    track_id,
    name,
    composer
FROM track
WHERE NOT (composer = 'AC/DC');


/*
如果需求是：

    Composer 不是 AC/DC
    或
    Composer 沒有資料

就必須明確寫：
*/

SELECT
    track_id,
    name,
    composer
FROM track
WHERE
    composer <> 'AC/DC'
    OR composer IS NULL;


/*
===============================================================================
16. <> 也不能自動包含 NULL
===============================================================================

這個很容易踩坑。

很多人會認為：

    composer <> 'AC/DC'

代表：

    所有不是 AC/DC 的歌曲。

但是 NULL 不會自動算進去。

如果：

    composer = NULL

那：

    NULL <> 'AC/DC'

結果：

    UNKNOWN

因此 WHERE 會排除這筆資料。
===============================================================================
*/


SELECT
    track_id,
    name,
    composer
FROM track
WHERE composer <> 'AC/DC';


/*
如果你真的要：

    不是 AC/DC
    或沒有 Composer

則寫：
*/

SELECT
    track_id,
    name,
    composer
FROM track
WHERE
    composer <> 'AC/DC'
    OR composer IS NULL;


/*
===============================================================================
17. NOT IN + NULL 的預告
===============================================================================

NULL 對 NOT IN 也會造成很容易誤判的結果。

例如：

    value NOT IN (...)

如果候選集合中包含 NULL，
整個條件可能出現 UNKNOWN。

完整的：

    IN
    NOT IN
    NULL

問題會在之後進階查詢時再次遇到。

Project 1 目前先建立：

    NULL 參與一般比較
        → 很可能得到 UNKNOWN

這個基本觀念即可。
===============================================================================
*/


/*
===============================================================================
18. NULL 與 ORDER BY
===============================================================================

前一個 Step 學過：

    ORDER BY

PostgreSQL 可以明確指定 NULL 放哪裡。

例如：

    NULLS LAST
===============================================================================
*/

SELECT
    track_id,
    name,
    composer
FROM track
ORDER BY
    composer ASC NULLS LAST;


/*
也可以：

    NULLS FIRST
*/

SELECT
    track_id,
    name,
    composer
FROM track
ORDER BY
    composer ASC NULLS FIRST;


/*
這是 PostgreSQL 的排序控制功能。

Project 1 目前只要知道存在即可。
*/


/*
===============================================================================
19. NULL Debug 方法
===============================================================================

如果查詢結果跟預期不同，
而條件涉及可能為 NULL 的欄位：

先單獨查看欄位。

例如：
===============================================================================
*/

SELECT
    composer
FROM track;


/*
再分別測：

    IS NULL
    IS NOT NULL
*/

SELECT
    composer
FROM track
WHERE composer IS NULL;


SELECT
    composer
FROM track
WHERE composer IS NOT NULL;


/*
這通常能快速發現：

    為什麼 WHERE 條件少了一些資料。
*/


