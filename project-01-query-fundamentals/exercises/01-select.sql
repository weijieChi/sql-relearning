/*
===============================================================================
01. SELECT *
===============================================================================

SELECT 是 SQL 中用來「查詢資料」的主要指令。

FROM 指定資料來源。

下面：

    SELECT *
    FROM track;

意思是：

    從 track Table 取得每一個欄位。

* 可以理解成：

    all columns

也就是把目前 Table 中所有欄位都放進查詢結果。

注意：

SELECT 本身不會刪除、修改或新增資料。

它只是「讀取」資料。
===============================================================================
*/

SELECT *
FROM track;


/*
===============================================================================
02. 只選擇需要的欄位
===============================================================================

大部分實際程式不需要 Table 的所有欄位。

例如目前只想知道：

    track_id
    name
    unit_price

就可以明確指定這三個欄位。

欄位之間使用逗號 , 分隔。

最後一個欄位後面不需要逗號。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price
FROM track;


/*
===============================================================================
03. SELECT 的欄位順序會影響結果顯示順序
===============================================================================

SELECT 中欄位的排列方式：

    name,
    track_id,
    unit_price

只會影響查詢結果的「欄位顯示順序」。

它不會修改原本 track Table 的 Schema。
===============================================================================
*/

SELECT
    name,
    track_id,
    unit_price
FROM track;


/*
===============================================================================
04. Column Alias：欄位別名
===============================================================================

AS 可以替「查詢結果中的欄位」取另一個名字。

例如：

    track_id AS id

查詢結果會顯示：

    id

但真正 Table 裡的欄位仍然叫：

    track_id

也就是 Alias 只存在於這一次查詢結果。

它不會執行：

    ALTER TABLE

也不會修改 Database Schema。
===============================================================================
*/

SELECT
    track_id AS id,
    name AS track_name,
    unit_price AS price
FROM track;


/*
===============================================================================
05. AS 可以省略
===============================================================================

PostgreSQL 允許：

    track_id id

而不用：

    track_id AS id

所以下面也是合法的。
===============================================================================
*/

SELECT
    track_id id,
    name track_name,
    unit_price price
FROM track;


/*
但是學習階段建議保留 AS：

    track_id AS id

理由不是因為 SQL 要求，而是：

    可讀性比較高。

看到 AS 就很容易知道：

    左邊 = 原始欄位 / Expression
    右邊 = Alias
*/


/*
===============================================================================
06. Table Alias：資料表別名
===============================================================================

Alias 不只能給 Column，也可以給 Table。

例如：

    FROM track AS t

代表：

    track 這張 Table
    在這次 SQL Query 中暫時叫 t。

因此可以寫：

    t.track_id
    t.name
    t.unit_price

`.` 可以理解成：

    Table.Column
===============================================================================
*/

SELECT
    t.track_id,
    t.name,
    t.unit_price
FROM track AS t;


/*
===============================================================================
07. Table Alias 不會重新命名資料表
===============================================================================

下面：

    FROM track AS t

只代表：

    在這一條 Query 中使用 t 代表 track。

Query 執行結束之後：

    track

仍然叫：

    track

Database 中不會突然多出一張叫 t 的 Table。
===============================================================================
*/

SELECT
    t.track_id AS id,
    t.name AS track_name,
    t.unit_price AS price
FROM track AS t;


/*
===============================================================================
08. Expression：計算欄位
===============================================================================

SELECT 不只能直接取得 Column。

也可以執行運算。

track.milliseconds 儲存的是歌曲長度，單位為：

    millisecond
    毫秒

1000 milliseconds = 1 second

因此：

    milliseconds / 1000.0

可以把毫秒轉換成秒。

注意：

這個結果只存在於 Query Result。

Database 中並沒有真的新增：

    duration_seconds

這個 Column。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds,
    milliseconds / 1000.0 AS duration_seconds
FROM track;


/*
===============================================================================
09. 將毫秒轉換成分鐘
===============================================================================

1 秒 = 1000 毫秒
1 分鐘 = 60 秒

所以：

    60 * 1000
    = 60000 milliseconds

因此可以：

    milliseconds / 60000.0

取得分鐘數。
===============================================================================
*/

SELECT
    track_id,
    name,
    milliseconds,
    milliseconds / 60000.0 AS duration_minutes
FROM track;


/*
===============================================================================
10. 為什麼這裡使用 60000.0？
===============================================================================

寫成：

    60000.0

可以清楚表達：

    我希望進行具有小數部分的計算。

例如歌曲：

    343719 milliseconds

除以：

    60000.0

結果約為：

    5.72865

分鐘。

後面學數值函式時，
我們會再使用 ROUND() 把它整理成：

    5.73
===============================================================================
*/

SELECT
    name,
    milliseconds / 60000.0 AS duration_minutes
FROM track;


/*
===============================================================================
11. 多個計算欄位
===============================================================================

同一個 SELECT 中可以建立多個 Expression。

下面同時顯示：

    原始毫秒
    秒
    分鐘
===============================================================================
*/

SELECT
    name,

    -- Database 中真正存在的欄位。
    milliseconds,

    -- Query 執行時計算出來的欄位。
    milliseconds / 1000.0 AS duration_seconds,

    -- Query 執行時計算出來的欄位。
    milliseconds / 60000.0 AS duration_minutes

FROM track;


/*
===============================================================================
12. 價格運算
===============================================================================

Expression 不限定只能處理時間。

例如 unit_price 是單價。

假設只想「模擬」價格乘以 2：

    unit_price * 2

這同樣不會修改 Database。

注意：

這不是 UPDATE。

track.unit_price 的真正值完全沒有改變。
===============================================================================
*/

SELECT
    track_id,
    name,
    unit_price,
    unit_price * 2 AS double_price
FROM track;


/*
===============================================================================
13. Expression 可以加括號
===============================================================================

括號可以：

1. 明確表示運算順序。
2. 增加複雜 Expression 的可讀性。

例如：

    (milliseconds / 1000.0) / 60

概念上同樣是：

    milliseconds / 60000.0
===============================================================================
*/

SELECT
    name,
    (milliseconds / 1000.0) / 60 AS duration_minutes
FROM track;


/*
===============================================================================
14. SELECT Literal
===============================================================================

SELECT 不一定必須搭配 FROM。

例如 PostgreSQL 可以直接：

    SELECT 1;

或：

    SELECT 'Hello';

這裡：

    1

是一個 Numeric Literal。

    'SQL'

是一個 String Literal。

這也是前面討論過的重要規則：

    '...' = String Literal
    "..." = Quoted Identifier
===============================================================================
*/

SELECT 1;

SELECT 'SQL';


/*
甚至可以進行單純計算。
*/

SELECT
    10 + 20 AS result;


/*
===============================================================================
15. Literal + Table Column
===============================================================================

Literal 也可以和 Table Query 一起使用。

下面每一列都會多出一個固定值：

    Chinook

這個值不是 track Table 裡面的 Column。

它只是 Query Result 的一部分。
===============================================================================
*/

SELECT
    track_id,
    name,
    'Chinook' AS source_database
FROM track;