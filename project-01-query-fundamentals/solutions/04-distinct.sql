/*
===============================================================================
Exercise 01
===============================================================================

題目：

列出 Customer 所有不同的 country。

DISTINCT：

移除查詢結果中重複的 country。

ORDER BY：

按照 country 由前往後排序。
===============================================================================
*/

SELECT DISTINCT
    country
FROM customer
ORDER BY country ASC;


/*
===============================================================================
Exercise 02
===============================================================================

題目：

列出 Customer 所有不同的：

    country
    city

組合。

重要：

DISTINCT 是針對：

    (country, city)

整個組合去重。

不是：

    country 各自去重
    city 各自去重。
===============================================================================
*/

SELECT DISTINCT
    country,
    city
FROM customer
ORDER BY
    country ASC,
    city ASC;


/*
===============================================================================
Exercise 03
===============================================================================

invoice 中可能有很多 Invoice 來自相同 billing_country。

DISTINCT 只保留不同的 billing_country。
===============================================================================
*/

SELECT DISTINCT
    billing_country
FROM invoice
ORDER BY billing_country ASC;


/*
===============================================================================
Exercise 04
===============================================================================

列出不同 Composer。

composer 可能包含 NULL。

PostgreSQL：

    NULLS LAST

可以明確要求 NULL 排到最後。
===============================================================================
*/

SELECT DISTINCT
    composer
FROM track
ORDER BY
    composer ASC NULLS LAST;


/*
===============================================================================
Exercise 05
===============================================================================

先使用 WHERE：

    只留下 USA、Canada、Brazil。

再：

    SELECT DISTINCT country

因此最後最多只會看到這三個不同 country。

如果其中某個國家沒有 Customer，
它自然不會出現在結果中。
===============================================================================
*/

SELECT DISTINCT
    country
FROM customer
WHERE country IN (
    'USA',
    'Canada',
    'Brazil'
)
ORDER BY country ASC;


/*
===============================================================================
Exercise 06
===============================================================================

先篩選：

    country = 'USA'

然後對：

    (country, city)

組合進行 DISTINCT。

因為 country 已固定為 USA，
主要是在找：

    USA 有哪些不同 city。
===============================================================================
*/

SELECT DISTINCT
    country,
    city
FROM customer
WHERE country = 'USA'
ORDER BY
    country ASC,
    city ASC;


/*
===============================================================================
Exercise 07
===============================================================================

COUNT(*)：

計算 customer Table 的所有 Rows。

這裡：

    customer_count

只是查詢結果 Alias。
===============================================================================
*/

SELECT
    COUNT(*) AS customer_count
FROM customer;


/*
===============================================================================
Exercise 08
===============================================================================

COUNT(DISTINCT country)：

先概念上去除重複 country，
再計算有多少個不同 country。

NULL 不會被 COUNT(column) 計算。
===============================================================================
*/

SELECT
    COUNT(DISTINCT country) AS country_count
FROM customer;


/*
===============================================================================
Exercise 09
===============================================================================

同一個 Query 同時計算：

    Customer 總數

以及：

    不同 Country 數量。

注意：

COUNT(*)：

    計算 Rows。

COUNT(DISTINCT country)：

    計算不同且非 NULL 的 country。
===============================================================================
*/

SELECT
    COUNT(*) AS customer_count,
    COUNT(DISTINCT country) AS country_count
FROM customer;


/*
===============================================================================
Exercise 10
===============================================================================

計算不同 Composer 數量。

COUNT(DISTINCT composer)：

1. 不重複計算相同 Composer。
2. 不會計算 composer IS NULL 的資料。
===============================================================================
*/

SELECT
    COUNT(DISTINCT composer) AS composer_count
FROM track;


/*
===============================================================================
Exercise 11 - Query A
===============================================================================

沒有 DISTINCT。

因此：

每一個 Track 都會輸出自己的 composer。

如果很多歌曲具有相同 Composer，
查詢結果自然會重複。
===============================================================================
*/

SELECT
    composer
FROM track;


/*
===============================================================================
Exercise 11 - Query B
===============================================================================

DISTINCT：

只在 Query Result 中保留不同 Composer。

它完全不會修改：

    track Table
    composer Column
    原始資料
===============================================================================
*/

SELECT DISTINCT
    composer
FROM track;


/*
===============================================================================
Exercise 11 - 答案說明
===============================================================================

1. A 為什麼有很多重複 Composer？

因為：

    每一個 Track 都是一個 Row。

不同 Track 可以擁有相同 Composer。


2. B 做了什麼？

DISTINCT 對 SELECT Result 中的 composer 去重。


3. 是否修改 track Table？

沒有。

SELECT DISTINCT 仍然只是：

    Query / Read Operation

不會修改資料。
===============================================================================
*/


/*
===============================================================================
Exercise 12 - Query A
===============================================================================

只有 country。

所以：

相同 country 可以被 DISTINCT 合併。
===============================================================================
*/

SELECT DISTINCT
    country
FROM customer;


/*
===============================================================================
Exercise 12 - Query B
===============================================================================

customer_id 是 Primary Key。

也就是每一個 Customer 的 customer_id 都是唯一值。

因此：

    (customer_id, country)

這個組合自然也是唯一的。

即使加入 DISTINCT，
也幾乎沒有 Row 可以被移除。
===============================================================================
*/

SELECT DISTINCT
    customer_id,
    country
FROM customer;


/*
===============================================================================
Exercise 12 - 答案說明
===============================================================================

DISTINCT 判斷的是：

    SELECT 中所有欄位的完整組合。

Query A：

    (country)

可能重複。

例如：

    Brazil
    Brazil
    Brazil

因此 DISTINCT 有作用。


Query B：

    (customer_id, country)

例如：

    1 | Brazil
    2 | Brazil
    3 | Brazil

雖然 country 相同，

但是：

    customer_id

每一筆都不同。

所以這三列完整組合仍然不同。

DISTINCT 不會把它們合併。
===============================================================================
*/


/*
===============================================================================
Additional Verification 01
===============================================================================

可以比較：

    COUNT(*)

和：

    COUNT(country)

如果 country 定義允許 NULL，
兩者可能不同。

COUNT(*)：

    所有 Rows。

COUNT(country)：

    country 不為 NULL 的 Rows。
===============================================================================
*/

SELECT
    COUNT(*) AS row_count,
    COUNT(country) AS non_null_country_count
FROM customer;


/*
===============================================================================
Additional Verification 02
===============================================================================

比較：

    SELECT DISTINCT composer

和：

    COUNT(DISTINCT composer)

前者：

    結果中可能包含一個 NULL。

後者：

    COUNT 不會把 NULL 算進去。
===============================================================================
*/

SELECT DISTINCT
    composer
FROM track
ORDER BY
    composer ASC NULLS LAST;


SELECT
    COUNT(DISTINCT composer) AS composer_count
FROM track;


/*
===============================================================================
本階段最重要的觀念
===============================================================================

1.

    SELECT country
    FROM customer;

表示：

    每一個 Customer 都輸出自己的 country。


2.

    SELECT DISTINCT country
    FROM customer;

表示：

    只保留不同的 country。


3.

    SELECT DISTINCT
        country,
        city
    FROM customer;

表示：

    對 (country, city) 整個組合去重。


4.

    DISTINCT

只改變 Query Result。

不會：

    DELETE
    UPDATE
    修改原始 Table。


5.

    COUNT(DISTINCT country)

表示：

    計算不同且非 NULL 的 country 數量。


6.

不要養成：

    「看到重複資料就直接加 DISTINCT」

的習慣。

應該先判斷：

    為什麼資料重複？

再確認：

    業務需求是不是真的需要去重？

===============================================================================
*/