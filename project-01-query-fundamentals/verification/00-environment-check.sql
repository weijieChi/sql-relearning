/*
===============================================================================
Project 01：單表查詢實驗室
Step 01：Environment Check
===============================================================================

用途：

確認目前：

1. PostgreSQL Server 可以正常連線。
2. Database 是 chinook。
3. Schema 是 public。
4. Chinook Tables 已成功建立。
5. Chinook Seed Data 已成功匯入。

這個檔案不是正式 SQL 練習題。

它是環境驗證工具。

之後如果：

- 重建 PostgreSQL Container
- 重新匯入 Database
- 換電腦
- 修改 Connection
- 懷疑自己連錯 Database

都可以再次執行這個檔案。
===============================================================================
*/


/*
------------------------------------------------------------------------------
01. 確認目前 Database
------------------------------------------------------------------------------

預期：

database_name
-------------
chinook
------------------------------------------------------------------------------
*/

SELECT
    current_database() AS database_name;


/*
------------------------------------------------------------------------------
02. 確認登入帳號
------------------------------------------------------------------------------

目前如果使用 postgres 連線：

預期：

login_user
----------
postgres

未來如果建立 sql_student，
這裡則會顯示 sql_student。
------------------------------------------------------------------------------
*/

SELECT
    current_user AS login_user;


/*
------------------------------------------------------------------------------
03. 查看目前 Schema

Chinook Tables 預設建立在 public schema。

預期：

schema_name
-----------
public
------------------------------------------------------------------------------
*/

SELECT
    current_schema() AS schema_name;


/*
------------------------------------------------------------------------------
04. 查看 PostgreSQL Server Version

version() 回傳 PostgreSQL Server 的完整版本資訊。

這裡查的是 Server，
不是 Windows 上 pgAdmin 或 psql 的版本。
------------------------------------------------------------------------------
*/

SELECT
    version();


/*
------------------------------------------------------------------------------
05. 一次取得主要環境資訊

實務上通常會像這樣一次查看。
------------------------------------------------------------------------------
*/

SELECT
    current_database() AS database_name,
    current_user AS login_user,
    current_schema() AS schema_name;


/*
------------------------------------------------------------------------------
06. 確認 Chinook 的 track Table 可以正常讀取

COUNT(*)：

計算查詢結果中的資料列數量。

目前不用深入學 COUNT。
正式 Aggregate Function 會在後面的 Project 再處理。

這裡只是把它當成驗證工具。
------------------------------------------------------------------------------
*/

SELECT
    COUNT(*) AS track_count
FROM track;


/*
------------------------------------------------------------------------------
07. 讀取 track 前 10 筆資料

目前只用來檢查資料是否真的存在。

LIMIT 10：

最多只回傳 10 Rows。

注意：

沒有 ORDER BY 時，
SQL 並不保證資料一定按照固定順序回傳。

ORDER BY 會在 Project 1 後續正式學習。
------------------------------------------------------------------------------
*/

SELECT
    track_id,
    name,
    album_id,
    media_type_id,
    genre_id,
    composer,
    milliseconds,
    bytes,
    unit_price
FROM track
LIMIT 10;


/*
------------------------------------------------------------------------------
08. 確認 customer Table
------------------------------------------------------------------------------
*/

SELECT
    customer_id,
    first_name,
    last_name,
    company,
    country,
    email
FROM customer
LIMIT 10;


/*
------------------------------------------------------------------------------
09. 確認 invoice Table

之後日期時間相關練習主要會使用這張 Table。
------------------------------------------------------------------------------
*/

SELECT
    invoice_id,
    customer_id,
    invoice_date,
    billing_country,
    total
FROM invoice
LIMIT 10;


/*
------------------------------------------------------------------------------
10. 查看 public Schema 中所有一般 Table

information_schema.tables 是 SQL 標準化的 Metadata View。

它描述 Database 中有哪些 Tables。

目前只需要知道：

我們不是在查 Chinook 的商業資料，
而是在查 Database 本身的結構資訊。
------------------------------------------------------------------------------
*/

SELECT
    table_name
FROM information_schema.tables
WHERE
    table_schema = 'public'
    AND table_type = 'BASE TABLE'
ORDER BY
    table_name;